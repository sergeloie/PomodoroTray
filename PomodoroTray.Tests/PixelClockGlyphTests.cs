    private static string[] Glyph(params string[] rows) => rows;

    private static bool[,] Parse(string[] rows)
    {
        int w = rows[0].Length;
        int h = rows.Length;
        var result = new bool[w, h];
        for (int y = 0; y < h; y++)
            for (int x = 0; x < w; x++)
                result[x, y] = rows[y][x] == '#';
        return result;
    }

    [Fact]
    public void Digit_glyphs_match_the_specified_pixel_patterns()
    {
        foreach (var (digit, rows) in Expected)
        {
            var glyph = PixelClock.GetDigitGlyph(digit);
            var expected = Parse(rows);

            Assert.Equal(7, glyph.GetLength(0));
            Assert.Equal(14, glyph.GetLength(1));

            for (int y = 0; y < 14; y++)
                for (int x = 0; x < 7; x++)
                    if (glyph[x, y] != expected[x, y])
                        Assert.Fail(
                            $"Глиф '{digit}' расходится с эталоном в ({x},{y}): " +
                            $"ожидалось {(expected[x, y] ? '#' : '.')}, получено {(glyph[x, y] ? '#' : '.')}");
        }
    }
